#include "ft_printf.h"

int	print_int(int n)
{
	int	count;

	if (n == -2147483648)
		return (print_str("-2147483648"));
	count = 0;
	if (n < 0)
	{
		count += print_char('-');
		n = -n;
	}
	return (count + print_nbr_base(n, "0123456789", 10));
}
